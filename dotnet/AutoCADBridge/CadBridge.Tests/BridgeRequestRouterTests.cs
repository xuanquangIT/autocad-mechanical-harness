    private static JsonElement Request(
        string method,
        JsonObject parameters,
        string? jobId = null,
        string? idempotencyKey = null)
    {
        var envelope = new JsonObject
        {
            ["schema_version"] = "1.13",
            ["method"] = method,
            ["request_id"] = $"request-{method}",
            ["params"] = parameters,
        };
        if (jobId is not null)
        {
            envelope["job_id"] = jobId;
        }

        if (idempotencyKey is not null)
        {
            envelope["idempotency_key"] = idempotencyKey;
        }

        return JsonSerializer.SerializeToElement(envelope);
    }

    private static string[] Strings(JsonNode? node) =>
        node!.AsArray().Select(item => item!.GetValue<string>()).ToArray();

    private sealed record HostCall(
        string Route,
        object? Request,
        CancellationToken CancellationToken);

    private sealed class FakeBridgeHost : IBridgeHost
    {
        public FakeBridgeHost(BridgeHostDescriptor descriptor)
        {
            Descriptor = descriptor;
        }

        public BridgeHostDescriptor Descriptor { get; }

        public BridgeHostStatus Status { get; init; } = new(true, "doc-1");

        public List<HostCall> Calls { get; } = [];

        public Dictionary<string, BridgeHostResult> Results { get; } =
            new(StringComparer.Ordinal);

        public ValueTask<BridgeHostStatus> GetStatusAsync(CancellationToken cancellationToken)
        {
            Calls.Add(new HostCall("status", null, cancellationToken));
            return ValueTask.FromResult(Status);
        }

        public ValueTask<BridgeHostResult> InspectDocumentAsync(
            InspectDocumentHostRequest request,
            CancellationToken cancellationToken) => Record("inspect_document", request, cancellationToken);

        public ValueTask<BridgeHostResult> InspectSemanticDrawingAsync(
            SemanticDrawingHostRequest request,
            CancellationToken cancellationToken) => Record("semantic_drawing", request, cancellationToken);

        public ValueTask<BridgeHostResult> InspectSelectionAsync(
            InspectSelectionHostRequest request,
            CancellationToken cancellationToken) => Record("inspect_selection", request, cancellationToken);

        public ValueTask<BridgeHostResult> PreviewAsync(
            PreviewHostRequest request,
            CancellationToken cancellationToken) => Record("preview", request, cancellationToken);

        public ValueTask<BridgeHostResult> ValidateRevisionAsync(
            RevisionValidationHostRequest request,
            CancellationToken cancellationToken) => Record("validate_revision", request, cancellationToken);

        public ValueTask<BridgeHostResult> CommitAsync(
            CommitHostRequest request,
            CancellationToken cancellationToken) => Record("commit", request, cancellationToken);

        public ValueTask<BridgeHostResult> RollbackAsync(
            RollbackHostRequest request,
            CancellationToken cancellationToken) => Record("rollback", request, cancellationToken);

        public ValueTask<BridgeHostResult> ExportAsync(
            ExportHostRequest request,
            CancellationToken cancellationToken) => Record("export", request, cancellationToken);

        private ValueTask<BridgeHostResult> Record(
            string route,
            object request,
            CancellationToken cancellationToken)
        {
            Calls.Add(new HostCall(route, request, cancellationToken));
            var result = Results.TryGetValue(route, out var configured)
                ? configured
                : BridgeHostResult.Success(new JsonObject { ["route"] = route });
            return ValueTask.FromResult(result);
        }
    }
