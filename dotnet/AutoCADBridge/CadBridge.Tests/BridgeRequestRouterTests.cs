    [Fact]
    public void CommitAuthorizationRejectsValidlyHashedAndSignedPreviousSchemaPlan()
    {
        const string secret = "previous-schema-secret";
        var planNode = JsonNode.Parse(
            """
            {"canonical_units":"mm","document_id":"doc_legacy","expected_revision":"sha256:revision","job_id":"job_legacy","operations":[],"plan_hash":null,"plan_id":"plan_legacy","profile_ref":"demo@1.0","schema_version":"1.12","validation_expectations":[]}
            """)!.AsObject();
        using (var unhashed = JsonDocument.Parse(planNode.ToJsonString()))
        {
            planNode["plan_hash"] = BridgeAuthorization.ComputePlanHash(unhashed.RootElement);
        }
        var planHash = planNode["plan_hash"]!.GetValue<string>();
        var expiresAt = new DateTimeOffset(2030, 1, 1, 0, 15, 0, TimeSpan.Zero);
        var claims = new JsonObject
        {
            ["approval_id"] = "approval_legacy",
            ["job_id"] = "job_legacy",
            ["document_id"] = "doc_legacy",
            ["expected_revision"] = "sha256:revision",
            ["plan_hash"] = planHash,
            ["approved_by"] = "engineer@example.com",
            ["expires_at"] = expiresAt.ToString("O"),
        };
        var payload = Convert.ToBase64String(Encoding.UTF8.GetBytes(claims.ToJsonString()))
            .TrimEnd('=')
            .Replace('+', '-')
            .Replace('/', '_');
        var signature = Convert.ToHexString(HMACSHA256.HashData(
            Encoding.UTF8.GetBytes(secret),
            Encoding.ASCII.GetBytes(payload))).ToLowerInvariant();
        using var planDocument = JsonDocument.Parse(planNode.ToJsonString());

        Assert.False(BridgeAuthorization.TryValidateCommitAuthorization(
            planDocument.RootElement,
            $"v2.{payload}.{signature}",
            secret,
            "job_legacy",
            "sha256:revision",
            expiresAt,
            out _));
    }

