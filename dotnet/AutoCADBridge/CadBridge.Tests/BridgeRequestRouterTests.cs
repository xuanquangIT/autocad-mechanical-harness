    [Fact]
    public async Task HandshakeAndStatusDeclareOnlyValidatedHostFacts()
    {
        var host = new FakeBridgeHost(DefaultDescriptor() with
        {
            Capabilities =
            [
                "stable_metadata",
                "commit",
                "document_lock",
                "atomic_transaction",
                "undo_group",
                "inspect_document",
            ],
            SupportedOperationTypes = ["create_line"],
        })
        {
            Status = new BridgeHostStatus(true, "doc-active", "ready"),
        };
        var router = new BridgeRequestRouter(host);

        var handshake = await router.HandleAsync(
            Request("handshake", new JsonObject { ["schema_version"] = "1.13" }),
            CancellationToken.None);

        Assert.Equal(IpcResponseStatus.Ok, handshake.Status);
        Assert.Equal("1.13", handshake.Data!["schema_version"]!.GetValue<string>());
        Assert.Equal(
            [
                "atomic_transaction",
                "commit",
                "document_lock",
                "inspect_document",
                "stable_metadata",
                "undo_group",
            ],
            Strings(handshake.Data["capabilities"]));
        Assert.Equal(["create_line"], Strings(handshake.Data["supported_operations"]));
        Assert.Equal("AutoCAD", handshake.Data["cad_application"]!.GetValue<string>());
        Assert.Equal("25.1", handshake.Data["cad_version"]!.GetValue<string>());
        Assert.Empty(host.Calls);

        var status = await router.HandleAsync(
            Request("status", new JsonObject()),
            CancellationToken.None);
        Assert.Equal(IpcResponseStatus.Ok, status.Status);
        Assert.True(status.Data!["available"]!.GetValue<bool>());
        Assert.Equal("doc-active", status.Data["active_document_id"]!.GetValue<string>());
        Assert.Equal("ready", status.Data["message"]!.GetValue<string>());
        Assert.Equal(["status"], host.Calls.Select(call => call.Route));
    }

